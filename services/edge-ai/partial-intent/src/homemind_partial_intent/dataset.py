PREFIXES = ("", "음, ", "지금 ", "그런데 ")
SUFFIXES = ("", "…", " 그래서 말인데", " 어떻게 하면 좋을까")


def _split_for_index(index: int, size: int) -> str:
    del size
    remainder = index % 6
    if remainder == 4:
        return "validation"
    if remainder == 5:
        return "test"
    return "train"


def build_seed_dataset(output: str | Path) -> dict[str, Any]:
    target = Path(output).resolve()
    target.mkdir(parents=True, exist_ok=True)
    all_rows: list[dict[str, Any]] = []
    for label in INTENTS:
        cues = CUES[label]
        for cue_index, cue in enumerate(cues):
            split = _split_for_index(cue_index, len(cues))
            group_id = f"{label.lower()}-{cue_index:02d}"
            variants = []
            for prefix in PREFIXES:
                variants.append(f"{prefix}{cue}")
            for suffix in SUFFIXES[1:]:
                variants.append(f"{cue}{suffix}")
            words = cue.split()
            if label != "NO_ACTION":
                from .features import SEMANTIC_TERMS

                variants.extend(
                    partial
                    for end in range(2, len(words))
                    if any(term in (partial := " ".join(words[:end])) for term in SEMANTIC_TERMS[label])
                )
            for variant_index, text in enumerate(dict.fromkeys(variants)):
                all_rows.append(
                    {
                        "sample_id": f"{group_id}-{variant_index:02d}",
                        "group_id": group_id,
                        "split": split,
                        "text": text,
                        "intent": label,
                        "is_partial": variant_index != len(variants) - 1,
                        "source": "AUTHORED_SYNTHETIC_V2",
                    }
                )
    for split in ("train", "validation", "test"):
        rows = [row for row in all_rows if row["split"] == split]
        path = target / f"{split}.jsonl"
        path.write_text(
            "".join(json.dumps(row, ensure_ascii=False) + "\n" for row in rows),
            encoding="utf-8",
        )
    report = {
        "source": "authored synthetic Korean seed set v2; not a natural-speech acceptance set",
        "rows": len(all_rows),
        "by_split": dict(Counter(row["split"] for row in all_rows)),
        "by_intent": dict(Counter(row["intent"] for row in all_rows)),
        "group_leakage": group_leakage(all_rows),
    }
    (target / "manifest.json").write_text(
        json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    return report


def load_rows(directory: str | Path, split: str) -> list[dict[str, Any]]:
    path = Path(directory) / f"{split}.jsonl"
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line]


def group_leakage(rows: list[dict[str, Any]]) -> list[str]:
    memberships: dict[str, set[str]] = {}
    for row in rows:
        memberships.setdefault(row["group_id"], set()).add(row["split"])
    return sorted(group for group, splits in memberships.items() if len(splits) > 1)
